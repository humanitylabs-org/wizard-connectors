"""Portable recipe/static hardening contracts; not Docker/WAM installation proof."""
import json
from pathlib import Path
import re
import unittest

ROOT=Path(__file__).resolve().parents[1]


class AlphaRecipeTests(unittest.TestCase):
    def test_fixed_alpha_version_every_service_and_api(self):
        version='0.2.0-alpha.1'
        config=json.loads((ROOT/'runtipi/config.json').read_text())
        self.assertEqual(config['version'],version)
        self.assertIn('version: '+version+'\n',(ROOT/'wizard.md').read_text())
        self.assertIn('package: image',(ROOT/'wizard.md').read_text())
        self.assertEqual(json.loads((ROOT/'openapi.json').read_text())['info']['version'],version)
        self.assertIn('"version":"'+version+'"',(ROOT/'app/server.py').read_text())
        self.assertIn("version:'"+version+"'",(ROOT/'web/app.js').read_text())
        compose=(ROOT/'runtipi/docker-compose.yml').read_text()
        self.assertEqual(compose.count('image: wizard-connectors:'+version+'\n'),5)
        self.assertEqual(compose.count('pull_policy: never'),5)
        self.assertNotIn('CONNECTORS_IMAGE',compose)
        self.assertNotRegex(compose,r'^\s+build:',msg='Alpha recipe must use the packaged native image')
        self.assertEqual(compose.count('<<: *security'),5)
        self.assertIn('cap_drop: [ALL]',compose)
        self.assertIn('read_only: true',compose)
        self.assertIn('no-new-privileges:true',compose)
        self.assertIn('tmpfs:',compose)
        self.assertIn('internal: true',compose)
        self.assertIn('WIZARD_TRUSTED_HOSTS:-}',compose)

    def test_ingress_joins_no_shared_main_network_and_is_the_calendar_endpoint(self):
        # WAM isolated mode: a `main` attachment makes the app `custom` (host-access consent) and
        # Calendar could not resolve the endpoint. The is_main service name is the advertised host.
        compose=(ROOT/'runtipi/docker-compose.yml').read_text()
        self.assertNotRegex(compose,r'(?m)^\s+main:')
        self.assertNotIn('WIZARD_MAIN_NETWORK',compose)
        self.assertNotIn('tipi_main_network',compose)
        self.assertNotIn('external: true',compose)
        self.assertNotRegex(compose,r'(?m)^  ingress:')
        block=compose.split('\n  wizard-connectors-calendar:\n',1)[1].split('\n  wizard-connectors:\n',1)[0]
        self.assertIn('is_main: true',block)
        self.assertIn('internal_port: 8799',block)
        self.assertIn('networks: [ingress-lane, edge]',block)
        self.assertIn('command: [python, app/ingress.py]',block)
        self.assertIn('<<: *security',block)

    def test_fresh_forms_need_only_autogenerated_required_passwords(self):
        fields=json.loads((ROOT/'runtipi/config.json').read_text())['form_fields']
        self.assertNotIn('CONNECTORS_IMAGE',{f['env_variable'] for f in fields})
        for field in fields:
            if field.get('required'):
                self.assertEqual(field['type'],'password')
                self.assertGreaterEqual(field['min'],32)
        secret=next(f for f in fields if f['env_variable']=='GOOGLE_STORE_SECRET')
        self.assertTrue(secret['required'])

    def test_calendar_provider_contract_remains_declared(self):
        manifest=(ROOT/'wizard.md').read_text()
        self.assertRegex(manifest,r'provides:\s*\[[^\]]*calendar-source[^\]]*\]')
        self.assertIn('id: connected-accounts',manifest)
        self.assertIn('incoming SHA-256 row for `wizard-calendar`',manifest)
        api=(ROOT/'docs/CALENDAR_API.md').read_text()
        self.assertIn('uses: [connected-accounts]',api)
        self.assertIn('uses: [calendar-source]',api)
        self.assertIn('provider_endpoints["connected-accounts"]',api)
