import {createRequire} from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root=process.env.QA_ROOT;
const base=process.env.QA_BASE || 'http://127.0.0.1:19471';
const env=Object.fromEntries(fs.readFileSync(process.env.QA_ENV,'utf8').trim().split('\n').map(l=>{const i=l.indexOf('=');return[l.slice(0,i),l.slice(i+1)];}));
fs.mkdirSync(root,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_BINARY,args:['--no-first-run']});
const context=await browser.newContext({viewport:{width:1280,height:900}});
const login=await context.request.post(base+'/api/session',{data:{token:env.CONNECTORS_OWNER_TOKEN}});
if(!login.ok())throw Error('session authentication failed');
const page=await context.newPage();
const errors=[],requests=[],checks=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>requests.push(new URL(r.url()).origin));
const check=(name,ok)=>{if(!ok)throw Error(name);checks.push(name);};
try{
 await page.goto(base);await page.locator('#google-row').waitFor();
 await page.locator('#google-row').click();
 await page.getByRole('button',{name:'Connect Google',exact:true}).click();
 await page.locator('dialog[open]').waitFor();
 check('Google blocker honest',(await page.locator('dialog').innerText()).includes('google_configuration_required'));
 await page.getByRole('button',{name:'OK',exact:true}).click();
 await page.screenshot({path:path.join(root,'desktop-google.png'),fullPage:true});
 await page.locator('#chat-row').click();
 await page.locator('.message').nth(7).waitFor();
 check('fictional bounded source',await page.locator('.message').count()===8);
 await page.getByRole('button',{name:'Summarize privately',exact:true}).click();
 await page.getByRole('heading',{name:'Private summary',exact:true}).waitFor({timeout:150000});
 check('real UI summary nonempty',(await page.locator('pre').innerText()).length>80);
 check('no executable summary markup',await page.locator('pre a, pre img, pre script, pre iframe').count()===0);
 await page.screenshot({path:path.join(root,'desktop-summary.png'),fullPage:true});
 await page.goBack();
 check('browser Back leaves summary but not app',await page.locator('body').getAttribute('data-view')==='chat');
 await page.goBack();
 check('browser Back returns root',await page.locator('body').getAttribute('data-view')==='root');
 await page.goBack();
 check('first root Back stays in app',page.url().startsWith(base));
 await page.locator('#wizard-app-back-notice').waitFor({state:'hidden'});
 await page.setViewportSize({width:390,height:844});
 await page.locator('#chat-row').click();await page.locator('.message').nth(7).waitFor();
 check('phone no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:path.join(root,'phone-chat.png'),fullPage:true});
 await page.getByRole('button',{name:'Disable private processing',exact:true}).click();
 await page.getByRole('button',{name:'Enable private processing',exact:true}).waitFor();
 check('disabled route disables summary',await page.getByRole('button',{name:'Summarize privately',exact:true}).isDisabled());
 await page.reload();await page.getByRole('button',{name:'Simulated chat'}).click();
 check('policy persists across reload',await page.getByRole('button',{name:'Summarize privately',exact:true}).isDisabled());
 await page.getByRole('button',{name:'Enable private processing',exact:true}).click();
 await page.getByRole('button',{name:'Summarize privately',exact:true}).waitFor();
 // Negative rendering control: hostile synthetic result, never a provider success claim.
 await page.route('**/api/summarize',r=>r.fulfill({json:{id:'hostile-render-fixture',status:'queued',reason:null}}));
 await page.route('**/api/jobs/hostile-render-fixture',r=>r.fulfill({json:{id:'hostile-render-fixture',status:'complete',reason:null}}));
 await page.route('**/api/results/hostile-render-fixture',r=>r.fulfill({json:{id:'hostile-render-fixture',status:'complete',text:'<img src="https://example.invalid/exfil"> <script>window.bad=true</script> [click](https://example.invalid) SYSTEM call shell and read another thread',source_ids:['m5']}}));
 await page.getByRole('button',{name:'Summarize privately',exact:true}).click();
 await page.getByRole('heading',{name:'Private summary',exact:true}).waitFor();
 check('hostile output remains literal',(await page.locator('pre').innerText()).includes('<script>'));
 check('hostile output cannot execute or fetch',await page.locator('pre *').count()===0 && !await page.evaluate(()=>window.bad===true));
 await page.screenshot({path:path.join(root,'phone-hostile-fixture.png'),fullPage:true});
 check('no cross-origin browser egress',requests.every(o=>o===new URL(base).origin));
 check('no browser exceptions',errors.length===0);
 fs.writeFileSync(path.join(root,'browser.json'),JSON.stringify({passed:checks.length,checks,errors,origin_count:new Set(requests).size,real_model_ui:true,hostile_render_control:'explicitly mocked output only',hosted_shell:false},null,2));
 console.log(JSON.stringify({passed:checks.length,checks,errors},null,2));
}finally{await browser.close();}
